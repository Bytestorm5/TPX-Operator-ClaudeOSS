// Builds the desktop badge, "Powered by Trusplex Operator" (md, dark ground),
// as one SVG after the Trusplex Badge component; writes hooks/badge-svg.ts.
import { readFileSync, writeFileSync } from 'node:fs'

const emblem = readFileSync(new URL('./assets/trusplex-emblem.svg', import.meta.url), 'utf8')
const defs = /<defs>([\s\S]*?)<\/defs>/.exec(emblem)[1].replace(/\s+/g, ' ').replace(/id="linear-gradient/g, 'id="tpx-e').replace(/url\(#linear-gradient/g, 'url(#tpx-e')
const paths = [...emblem.matchAll(/<path[^>]*><\/path>/g)].map(m => m[0].replace(/url\(#linear-gradient/g, 'url(#tpx-e').replace('></path>', '/>')).join('')
const W = 268, H = 34
const svg =
  `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}">` +
  `<defs>${defs}` +
  `<linearGradient id="tpx-ring" x1="0" x2="1" y1="0" y2="0"><stop offset="0" stop-color="#746DF8"/><stop offset=".55" stop-color="#1C83EA"/><stop offset="1" stop-color="#0039D8"/></linearGradient>` +
  `<linearGradient id="tpx-wash" x1="0" x2="1" y1="0" y2="0"><stop offset="0" stop-color="#746DF8" stop-opacity=".28"/><stop offset=".7" stop-color="#746DF8" stop-opacity="0"/></linearGradient>` +
  `</defs>` +
  `<rect x="1" y="1" width="${W - 2}" height="${H - 2}" rx="${(H - 2) / 2}" fill="#0B0B1B"/>` +
  `<rect x="1" y="1" width="${W - 2}" height="${H - 2}" rx="${(H - 2) / 2}" fill="url(#tpx-wash)" stroke="url(#tpx-ring)" stroke-width="2"/>` +
  `<svg x="10" y="8" width="18" height="18" viewBox="0 0 894.27 842.1">${paths}</svg>` +
  `<text x="36" y="21.5" font-family="Geist, system-ui, -apple-system, sans-serif" font-size="14" letter-spacing="-0.14">` +
  `<tspan fill="#D3D6E0">Powered by </tspan><tspan fill="#FFFFFF" font-weight="600">Trusplex Operator</tspan></text></svg>`
writeFileSync(
  new URL('../hooks/badge-svg.ts', import.meta.url),
  `// Generated by dev/make-badge-svg.mjs from the Trusplex emblem: do not edit by hand.\n\n` +
    `export const BADGE_SVG_WIDTH = ${W}\nexport const BADGE_SVG_HEIGHT = ${H}\nexport const BADGE_SVG =\n  ${JSON.stringify(svg)}\n`,
)
writeFileSync(new URL('./assets/badge.svg', import.meta.url), svg)
console.log(`svg badge: ${svg.length} chars`)
